  await ensureAvailableStock(page, 'VP-01-02', 'Kho Hà Nội', 1)
  await page.goto('/ban-hang/moi')
  await page.getByLabel('Khách hàng', { exact: true }).selectOption({ label: name })
  await page.getByLabel('Kho thực hiện').selectOption({ label: 'Kho Hà Nội' })
  const product = page.getByLabel('Sản phẩm 1', { exact: true })
  await product.selectOption((await product.getByRole('option', { name: /^VP-01-02/ }).getAttribute('value'))!)
  await page.getByLabel('Số lượng', { exact: true }).fill('1')
  await page.getByLabel('Đơn giá (VND)', { exact: true }).fill('30000')
  await page.getByRole('button', { name: 'Lưu đơn nháp', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^SO-/ })).toBeVisible()
  const orderUrl = page.url()
  const exposure = page.getByRole('region', { name: 'Hạn mức công nợ hiện tại', exact: true })
  await expect(exposure.locator('div').filter({ has: page.getByText('Đã sử dụng', { exact: true }) }).locator('dd')).toHaveText('0 VND')
  await expect(exposure.locator('div').filter({ has: page.getByText('Sau duyệt đơn này', { exact: true }) }).locator('dd')).toHaveText('30.000 VND')
  await page.getByRole('button', { name: 'Gửi duyệt', exact: true }).click()
  await expect(page.locator('.page-heading .badge')).toHaveText('Chờ duyệt')
  await expect(page.getByRole('button', { name: 'Phê duyệt đơn', exact: true })).toBeEnabled()
