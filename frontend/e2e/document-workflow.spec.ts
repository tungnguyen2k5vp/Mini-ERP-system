test('stale order edit preserves local content until explicit discard and reload', async ({ page, context }, testInfo) => {
  await login(page)
  const url = await createOrder(page)
  await page.getByRole('button', { name: 'Sửa đơn nháp', exact: true }).click()
  await page.getByLabel('Ghi chú', { exact: true }).fill('Nội dung chưa lưu tại thẻ đầu')
  await captureEditor(page, name => testInfo.outputPath(name), 'order-editor')
  const other = await context.newPage()
  await other.goto(url)
  await saveOrderNote(other, 'Nội dung mới tại thẻ thứ hai')
  const conflict = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().includes('/orders/'))
  await page.getByRole('button', { name: 'Lưu đơn nháp', exact: true }).click()
  expect((await conflict).status()).toBe(409)
  await expect(page.getByLabel('Ghi chú', { exact: true })).toHaveValue('Nội dung chưa lưu tại thẻ đầu')
  page.once('dialog', dialog => void dialog.accept())
  await page.getByRole('button', { name: 'Bỏ thay đổi và tải bản mới', exact: true }).click()
  await expect(page.getByText('Nội dung mới tại thẻ thứ hai', { exact: true })).toBeVisible()
  await other.close()
})

