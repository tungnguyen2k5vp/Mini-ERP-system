async function createOrder(page: Page) {
  await page.goto('/mua-hang/moi')
  await page.getByLabel('Nhà cung cấp', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Kho thực hiện').selectOption({ index: 1 })
  await page.getByLabel('Sản phẩm 1', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Ngày dự kiến').fill('2025-01-01')
  await page.getByLabel('Ghi chú', { exact: true }).fill('Nháp kiểm tra quy trình')
  await page.getByRole('button', { name: 'Lưu đơn nháp', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^PO-/ })).toBeVisible()
  return page.url()
}

async function saveOrderNote(page: Page, note: string) {
  await page.getByRole('button', { name: 'Sửa đơn nháp', exact: true }).click()
  await page.getByLabel('Ghi chú', { exact: true }).fill(note)
  await page.getByRole('button', { name: 'Lưu đơn nháp', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^PO-/ })).toBeVisible()
}

async function captureEditor(page: Page, outputPath: (name: string) => string, name: string) {
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 900 })
    const measured = await page.evaluate(() => innerWidth)
    if (measured !== width) await page.setViewportSize({
      width: Math.round(width * width / measured), height: Math.round(900 * width / measured),
    })
    await expect.poll(() => page.evaluate(() => innerWidth)).toBe(width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0)
    await page.screenshot({ path: outputPath(`${name}-${width}.png`), fullPage: true })
  }
}

async function reasonAction(page: Page, action: string, reasonLabel: string, reason: string) {
  await page.getByRole('button', { name: action, exact: true }).click()
  await expect(page.getByRole('button', { name: 'Xác nhận', exact: true })).toBeDisabled()
  await page.getByLabel(reasonLabel, { exact: true }).fill(reason)
  page.once('dialog', dialog => void dialog.accept())
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click()
}

