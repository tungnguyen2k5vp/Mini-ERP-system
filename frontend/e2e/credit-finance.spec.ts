  await page.getByLabel('Lý do duyệt vượt hạn mức', { exact: true }).fill('Được xác nhận thanh toán trong ngày')
  await captureForm(page, name => testInfo.outputPath(name), 'order-credit-override')
  const approved = page.waitForResponse(response => response.request().method() === 'POST' && /\/orders\/\d+\/approve$/.test(response.url()))
  await confirm(page, 'Xác nhận')
  const approval = await approved
  expect(approval.status(), `Approval ${approval.status()}: ${await approval.text()}`).toBe(200)
  await expect(page.locator('.page-heading .badge')).toHaveText('Đã duyệt')
  await page.locator('input[id^="fulfill-"]').fill('1')
  await confirm(page, 'Ghi sổ giao hàng')
  await expect(page.locator('.page-heading .badge')).toHaveText('Hoàn thành')
  await expect(page.getByText('Sau duyệt đơn này', { exact: true })).toHaveCount(0)
  await page.goto('/tai-chinh?direction=1')
  await page.getByRole('combobox', { name: 'Lọc đối tác', exact: true }).selectOption(partnerId)
  await page.getByRole('button', { name: 'Lập phiếu thanh toán', exact: true }).click()
  await page.getByLabel('Phương thức', { exact: true }).selectOption({ index: 1 })
  await page.getByRole('spinbutton', { name: /^Phân bổ hóa đơn/ }).fill('30000')
  const paid = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/finance/payments'))
  await confirm(page, 'Ghi sổ thanh toán')
  const paymentId = (await (await paid).json()).id
  await page.getByRole('tab', { name: 'Thu · chi', exact: true }).click()
  await page.getByRole('button', { name: `Đảo phiếu #${paymentId}`, exact: true }).click()
  await expect(page.getByRole('button', { name: 'Xác nhận đảo phiếu', exact: true })).toBeDisabled()
  await page.getByLabel('Lý do đảo phiếu', { exact: true }).fill('Sai phiếu ngân hàng, cần ghi nhận lại')
  await captureForm(page, name => testInfo.outputPath(name), 'payment-correction')
  const ids: string[] = []
  await page.route(`**/api/v1/finance/payments/${paymentId}/reverse`, async route => {
    ids.push(route.request().postDataJSON().requestId)
    const response = await route.fetch()
    if (ids.length === 1) return route.abort('failed')
    await route.fulfill({ response })
  })
  await confirm(page, 'Xác nhận đảo phiếu')
  await expect(page.getByRole('alert')).toContainText('Mất kết nối')
  await confirm(page, 'Xác nhận đảo phiếu')
