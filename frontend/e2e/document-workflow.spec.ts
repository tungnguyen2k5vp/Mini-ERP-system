  const documentUrl = page.url()
  await page.goto('/nguoi-dung')
  await page.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click()
  const form = page.locator('main form')
  const email = `workflow-warehouse-${randomBytes(5).toString('hex')}@minierp.example`
  const password = randomBytes(24).toString('base64') + 'Aa7!'
  await form.getByLabel('Họ và tên').fill('Kiểm tra sửa phiếu kho')
  await form.getByLabel('Email').fill(email)
  await form.getByLabel('Mật khẩu ban đầu').fill(password)
  await form.getByLabel('Vai trò').selectOption('Warehouse Staff')
  const created = page.waitForResponse(response => response.url().endsWith('/api/v1/users') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click()
  expect((await created).status()).toBe(201)
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password)
